import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8')
const csp = read('../src/renderer/index.html')
const apiConfig = read('../src/renderer/services/apiConfig.ts')
const authApi = read('../src/renderer/services/authApi.ts')
const main = read('../src/main/main.ts')
const updaterManager = read('../src/main/updater/updateManager.ts')
const updaterTransport = read('../src/main/updater/updateTransport.ts')
const updaterVerifier = read('../src/main/updater/manifestVerifier.ts')
const updaterTrust = read('../src/main/updater/updateTrust.ts')
const updaterPolicy = read('../src/main/updater/updateUtils.ts')
const vercel = JSON.parse(read('../vercel.json'))
const builder = read('../electron-builder.yml')
const electronViteConfig = read('../electron.vite.config.ts')
const packageJson = JSON.parse(read('../package.json'))
const packageLock = JSON.parse(read('../package-lock.json'))

assert.equal((csp.match(/Content-Security-Policy/g) ?? []).length, 1)
assert.match(csp, /connect-src 'self' https:\/\/admin-anceryx\.site wss:\/\/admin-anceryx\.site https:\/\/api\.anceryx\.site wss:\/\/api\.anceryx\.site/)
assert.match(csp, /https:\/\/static\.klipy\.com https:\/\/static1\.klipy\.com https:\/\/static2\.klipy\.com/)
assert.doesNotMatch(csp, /connect-src[^;]*\s(?:https:|wss:)(?:\s|;)/)
assert.match(apiConfig, /PRODUCTION_API_URL = 'https:\/\/admin-anceryx\.site'/)
assert.match(apiConfig, /PRODUCTION_WEB_API_URL = 'https:\/\/api\.anceryx\.site'/)
assert.doesNotMatch(apiConfig, /const importMeta = import\.meta/)
assert.match(authApi, /request failed before receiving a response/)
assert.match(authApi, /apiOrigin: redactConnectionOrigin\(API_BASE_URL\)/)
assert.match(main, /protocol\.registerSchemesAsPrivileged/)
assert.match(main, /loadURL\('app:\/\/anceryx\/index\.html'\)/)
assert.match(main, /app\.setName\('Anceryx'\)/)
assert.match(main, /const OAUTH_SCHEME = 'anceryx'/)
assert.match(main, /frame-ancestors 'none'/)
assert.doesNotMatch(csp, /frame-ancestors/)
assert.ok(vercel.headers.flatMap((rule) => rule.headers).some((header) => header.key.toLowerCase() === 'content-security-policy' && header.value.includes("frame-ancestors 'none'")))
assert.match(electronViteConfig, /context\.server[\s\S]*unsafe-inline[\s\S]*unsafe-eval/)
assert.match(builder, /copyright: "Copyright © 2026 Anceryx/)
assert.doesNotMatch(builder, /\u00C2\u00A9|\u00C3/)
assert.doesNotMatch(builder, /^publish:\s*$/m)
assert.doesNotMatch(builder, /provider:\s*github|owner:\s*Anceryx|repo:\s*Anceryx-App/)
assert.match(main, /new UpdateManager\(\)/)
assert.match(updaterManager, /fetchVerifiedUpdateManifest[\s\S]*UPDATE_MANIFEST_PUBLIC_KEY_PEM/)
assert.match(updaterManager, /verifyDownloadedInstallerFile[\s\S]*shell\.openPath/)
assert.match(updaterTransport, /verifySignedUpdateManifest/)
assert.match(updaterVerifier, /createPublicKey[\s\S]*verify\(/)
assert.match(updaterTrust, /MCowBQYDK2VwAyEAWtvd5\/en3Vvs5GxfJ4uNLcVof2CoB33qU4D\+CKf9EKc=/)
assert.match(updaterPolicy, /UPDATE_MANIFEST_SIGNATURE_VERIFICATION_ENABLED\s*=\s*false/)
assert.equal(packageJson.dependencies?.['electron-updater'], undefined)
assert.equal(packageJson.devDependencies?.['electron-updater'], undefined)
assert.equal(packageLock.packages['node_modules/electron-updater'], undefined)
assert.doesNotMatch(apiConfig, /127\.0\.0\.1|resolveQaApiBaseUrl/)
assert.doesNotMatch(main, /Anceryx QA|anceryx-qa/)
assert.doesNotMatch(electronViteConfig, /VITE_ANCERYX_QA|ANCERYX_QA_ENV_DIR|127\.0\.0\.1/)

console.log('connection, signed-manifest updater and release configuration checks passed')
