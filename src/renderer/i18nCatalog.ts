export type TranslationKey = keyof typeof messages['pt-BR']
export type AppLocale = keyof typeof messages

export function translate(key: string, locale: AppLocale, values: Record<string, string | number> = {}): string {
  const catalog = messages[locale] as Record<string, string>
  const template = catalog[key] ?? messages['pt-BR'][key as TranslationKey] ?? catalog['common.translationUnavailable']
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (placeholder, name: string) => name in values ? String(values[name]) : placeholder)
}

export function translatePlural(key: PluralTranslationKey, locale: AppLocale, count: number): string {
  const form = new Intl.PluralRules(locale).select(count)
  const variants = pluralMessages[locale][key]
  const template = variants[form as keyof typeof variants] ?? variants.other
  return template.replace('{count}', new Intl.NumberFormat(locale).format(count))
}

