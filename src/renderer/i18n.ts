export type TranslationKey = keyof typeof messages['pt-BR']
export type AppLocale = keyof typeof messages

export function translate(key: TranslationKey, locale: AppLocale): string {
  return messages[locale][key] ?? messages['pt-BR'][key]
}

export function useTranslation() {
  const locale = useUIStore((state) => state.locale)
  return (key: TranslationKey) => translate(key, locale)
}

